def process_image(image_path: str | Path, params: Params | None = None) -> LowPolyMesh:
    p = params or Params()
    img = cv2.imread(str(image_path), cv2.IMREAD_GRAYSCALE)
    if img is None:
        raise FileNotFoundError(f"Не удалось прочитать изображение: {image_path}")

    mask = binarize(img, p)
    components = _find_components(mask, p)
    if not components:
        raise ValueError(
            "Не найдено ни одной подходящей области. "
            "Проверьте threshold/invert/min_area_px."
        )

    all_verts = []
    all_faces = []
    n_holes = 0
    vert_offset = 0

    for comp in components:
        outer = _simplify(comp["outer"], p.simplify_px)
        holes = [_simplify(h, p.simplify_px) for h in comp["holes"]]
        holes = [h for h in holes if len(h) >= 3]
        n_holes += len(holes)

        verts2d, tris = _triangulate_with_holes(outer, holes)
        faces = _merge_triangles_to_quads(verts2d, tris, p)
        faces = drop_degenerate_faces(verts2d, faces)
        faces = _fix_winding(verts2d, faces)

        all_verts.append(verts2d)
        all_faces.extend(tuple(v + vert_offset for v in f) for f in faces)
        vert_offset += len(verts2d)

    verts2d = np.concatenate(all_verts, axis=0)

    # Y в изображениях растёт вниз, в 3D-мире обычно вверх — переворачиваем
    verts2d = verts2d.copy()
    verts2d[:, 1] = -verts2d[:, 1]

    if p.center:
        bbox_min = verts2d.min(axis=0)
        bbox_max = verts2d.max(axis=0)
        center = (bbox_min + bbox_max) / 2.0
        verts2d = verts2d - center

    verts2d = verts2d * p.scale
    verts3d = np.concatenate([verts2d, np.zeros((len(verts2d), 1))], axis=1)

    return LowPolyMesh(
        vertices=verts3d,
        faces=all_faces,
        n_components=len(components),
        n_holes=n_holes,
    )


def process_image_quad(image_path: str | Path, params: Params | None = None) -> LowPolyMesh:
    """Рекомендуемый пайплайн для завитков/лент/каллиграфии — ПРИШЁЛ НА
    СМЕНУ topology="ribbon" в ribbon_topology.py.

    Тот (skeleton/medial-axis) подход систематически давал
    самопересечения на реальных картинках: несколько независимых
    источников багов (направление left/right, адаптивное слияние узлов,
    искажение distance transform у развилок, miter-проблема при сходе
    нескольких лент в одну точку) — при том, что каждый по отдельности
    чинился, вместе они не давали гарантии отсутствия пересечений в
    принципе, поскольку вся геометрия СИНТЕЗИРОВАЛАСЬ из скелета заново.

    Этот пайплайн вместо этого:
        1. Строит earcut-триангуляцию РЕАЛЬНОГО контура (тот же
           проверенный метод, что в process_image / topology="fill") —
           самопересечение здесь математически невозможно, пока контур
           от cv2.findContours простой (а он всегда простой).
        2. Контуры (внешний и дырки) передискретизируются с сохранением
           острых углов (resample_contour_corner_aware) — учитывает
           именно "углы", как и просили: они всегда остаются отдельными
           вершинами, сглаживание Subdivision их не тронет.
        3. Треугольники сливаются в квады по ПРИОРИТЕТУ "квадратности"
           (_merge_triangles_to_quads_quality), а не жадно как попало —
           грани получаются ближе к квадратам/прямоугольникам, и
           минимальным числом (каждое успешное слияние уменьшает
           итоговый счётчик граней на единицу).

    Итоговая сетка — реальная триангулированная форма плюс
    merge-в-квады поверх неё, поэтому после Subdivision Surface должна
    точно повторять исходный силуэт (в отличие от skeleton-подхода,
    который синтезировал геометрию заново и был подвержен ошибкам
    оценки локальной ширины).
    """
    p = params or Params()
    img = cv2.imread(str(image_path), cv2.IMREAD_GRAYSCALE)
    if img is None:
        raise FileNotFoundError(f"Не удалось прочитать изображение: {image_path}")

    mask = binarize(img, p)
    components = _find_components(mask, p)
    if not components:
        raise ValueError(
            "Не найдено ни одной подходящей области. "
            "Проверьте threshold/invert/min_area_px."
        )

    all_verts = []
    all_faces = []
    n_holes = 0
    vert_offset = 0

    for comp in components:
        outer = resample_contour_corner_aware(comp["outer"], p.corner_epsilon_px, p.target_edge_px)
        holes = [
            resample_contour_corner_aware(h, p.corner_epsilon_px, p.target_edge_px)
            for h in comp["holes"]
        ]
        holes = [h for h in holes if len(h) >= 3]
        n_holes += len(holes)

        verts2d, tris = _triangulate_with_holes(outer, holes, p.target_edge_px)
        faces = _merge_triangles_to_quads_quality(verts2d, tris, p)
        faces = drop_degenerate_faces(verts2d, faces)
        faces = _fix_winding(verts2d, faces)

        all_verts.append(verts2d)
        all_faces.extend(tuple(v + vert_offset for v in f) for f in faces)
        vert_offset += len(verts2d)

    verts2d = np.concatenate(all_verts, axis=0)
    verts2d = verts2d.copy()
    verts2d[:, 1] = -verts2d[:, 1]

    if p.center:
        bbox_min = verts2d.min(axis=0)
        bbox_max = verts2d.max(axis=0)
        center = (bbox_min + bbox_max) / 2.0
        verts2d = verts2d - center

    verts2d = verts2d * p.scale
    verts3d = np.concatenate([verts2d, np.zeros((len(verts2d), 1))], axis=1)

    return LowPolyMesh(
        vertices=verts3d,
        faces=all_faces,
        n_components=len(components),
        n_holes=n_holes,
    )


