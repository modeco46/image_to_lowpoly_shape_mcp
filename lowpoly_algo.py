"""
lowpoly_algo.py — Layer A

Чистый алгоритм: растровое изображение (силуэт/орнамент) -> плоская
низкополигональная сетка (Z=0) с квадами там, где это возможно.

Никаких зависимостей от MCP, LM Studio или Blender/bpy — только
cv2 / numpy / shapely / mapbox_earcut. Это позволяет гонять и проверять
слой А отдельным скриптом, до того как он вообще подключается к Blender.

Пайплайн:
    1. Загрузка изображения, приведение к grayscale
    2. Бинаризация (threshold, опционально invert)
    3. Морфология (open/close) для подавления шума маски
    4. cv2.findContours с полной иерархией (RETR_CCOMP/RETR_TREE) ->
       группировка контуров по компонентам: внешний контур + его дырки
    5. Упрощение каждого контура (Douglas-Peucker, cv2.approxPolyDP)
    6. Фильтрация мелких контуров по площади (min_area_px)
    7. Триангуляция полигона с дырками (mapbox_earcut, ear clipping,
       точное соответствие границе — важно для CAD/ювелирной точности)
    8. Жадное слияние соседних треугольников в квады, где это даёт
       выпуклый и не слишком перекошенный четырёхугольник
    9. Масштабирование (px -> world units) и опциональное центрирование
   10. Экспорт в OBJ (плоская сетка, Z = 0)

Единицы: результат — plain OBJ. Дальше это либо импортируется в Blender
через существующий Blender MCP (execute_blender_code / wm.obj_import),
либо используется как угодно ещё — сам алгоритм об этом не знает.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from pathlib import Path

import cv2
import numpy as np


# --------------------------------------------------------------------------
# Результирующий mesh
# --------------------------------------------------------------------------

@dataclass
class LowPolyMesh:
    vertices: np.ndarray            # (N, 3) float64, Z всегда 0
    faces: list[tuple[int, ...]]    # индексы (0-based), длина 3 или 4
    n_components: int
    n_holes: int

    @property
    def n_quads(self) -> int:
        return sum(1 for f in self.faces if len(f) == 4)

    @property
    def n_tris(self) -> int:
        return sum(1 for f in self.faces if len(f) == 3)

    def stats(self) -> dict:
        return {
            "components": self.n_components,
            "holes": self.n_holes,
            "vertices": int(len(self.vertices)),
            "faces": len(self.faces),
            "quads": self.n_quads,
            "tris": self.n_tris,
        }

    def to_obj(self, path: str | Path) -> None:
        path = Path(path)
        lines = ["# generated by lowpoly_algo.py"]
        for v in self.vertices:
            lines.append(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}")
        for f in self.faces:
            idx = " ".join(str(i + 1) for i in f)  # OBJ is 1-indexed
            lines.append(f"f {idx}")
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")


# --------------------------------------------------------------------------
# Параметры
# --------------------------------------------------------------------------

@dataclass
class Params:
    threshold: float = 127.0          # порог бинаризации, 0-255
    invert: bool = False              # инвертировать маску (белое на чёрном)
    blur: int = 0                     # gaussian blur kernel (0 = выкл, нечётное >=3)
    morph_size: int = 3               # размер ядра open/close, 0 = выкл
    simplify_px: float = 2.0          # epsilon Douglas-Peucker, в пикселях
    min_area_px: float = 80.0         # отбрасывать контуры меньше этой площади
    corner_angle_deg: float = 35.0    # ниже этого угла вершина считается "острой"
                                       # и не сливается при упрощении соседних квадов
    quad_merge_angle_tol_deg: float = 25.0  # допуск на "не выпуклость" квада
    target_edge_px: float = 18.0      # желаемый шаг точек на изогнутых участках контура (px) — управляет плотностью/числом квадов
    corner_epsilon_px: float = 4.0    # порог approxPolyDP для углов — они ВСЕГДА сохраняются как отдельные вершины
    scale: float = 0.01               # px -> world units
    center: bool = True               # центрировать по bbox
    max_parts: int = 32               # защита от мусорных масок с кучей мелких компонент


# --------------------------------------------------------------------------
# Шаги 1-4: маска и иерархия контуров
# --------------------------------------------------------------------------

def binarize(gray: np.ndarray, p: Params) -> np.ndarray:
    if p.blur and p.blur >= 3:
        k = p.blur | 1  # нечётное
        gray = cv2.GaussianBlur(gray, (k, k), 0)

    _, mask = cv2.threshold(gray, p.threshold, 255, cv2.THRESH_BINARY)
    if p.invert:
        mask = 255 - mask

    if p.morph_size and p.morph_size > 0:
        k = np.ones((p.morph_size, p.morph_size), np.uint8)
        mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, k)
        mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, k)
    return mask


def _find_components(mask: np.ndarray, p: Params):
    """
    Возвращает список компонент вида:
        {"outer": Nx2 array, "holes": [Mx2 array, ...]}
    используя иерархию cv2.findContours (RETR_CCOMP: два уровня —
    внешние контуры и их непосредственные дырки).
    """
    contours, hierarchy = cv2.findContours(
        mask, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_SIMPLE
    )
    if hierarchy is None:
        return []
    hierarchy = hierarchy[0]  # (N, 4): next, prev, first_child, parent

    components = []
    for i, h in enumerate(hierarchy):
        parent = h[3]
        if parent != -1:
            continue  # это дырка, обработаем через родителя
        area = cv2.contourArea(contours[i])
        if area < p.min_area_px:
            continue
        outer = contours[i].reshape(-1, 2).astype(np.float64)

        holes = []
        child = h[2]
        while child != -1:
            hole_area = cv2.contourArea(contours[child])
            if hole_area >= p.min_area_px:
                holes.append(contours[child].reshape(-1, 2).astype(np.float64))
            child = hierarchy[child][0]  # next sibling

        components.append({"outer": outer, "holes": holes, "area": area})

    components.sort(key=lambda c: -c["area"])
    if p.max_parts > 0:
        components = components[: p.max_parts]
    return components


def _simplify(contour: np.ndarray, epsilon_px: float) -> np.ndarray:
    if epsilon_px <= 0:
        return contour
    c = contour.reshape(-1, 1, 2).astype(np.float32)
    approx = cv2.approxPolyDP(c, epsilon_px, closed=True)
    pts = approx.reshape(-1, 2).astype(np.float64)
    if len(pts) < 3:
        return contour  # упрощение выродило контур — не трогаем
    return pts


def resample_contour_corner_aware(
    contour: np.ndarray, corner_epsilon_px: float, target_edge_px: float
) -> np.ndarray:
    """Адаптивная передискретизация замкнутого контура для качественной
    квадовой топологии после Subdivision.

    Острые углы (найденные через approxPolyDP с corner_epsilon_px)
    ВСЕГДА сохраняются как отдельные вершины без изменений — Subdivision
    их не сгладит, раз они явно представлены в контрольной сетке между
    двумя короткими рёбрами. Между соседними углами вдоль ИСХОДНОЙ
    (плотной, попиксельной) дуги контура расставляются дополнительные
    точки с шагом ~target_edge_px по длине дуги — так изогнутые участки
    получают ровно столько точек, сколько нужно, чтобы после сглаживания
    форма осталась похожа на оригинал, а прямые участки между близкими
    углами не получают лишних точек вообще (минимизация числа квадов).
    """
    contour = contour.astype(np.float64)
    n = len(contour)
    if n < 3:
        return contour

    approx = cv2.approxPolyDP(
        contour.astype(np.float32).reshape(-1, 1, 2), corner_epsilon_px, closed=True
    )
    corner_pts = approx.reshape(-1, 2)
    if len(corner_pts) < 3:
        corner_pts = contour[:: max(1, n // 8)]

    corner_indices = []
    for cp in corner_pts:
        d = np.sum((contour - cp) ** 2, axis=1)
        corner_indices.append(int(np.argmin(d)))
    seen = set()
    uniq = []
    for idx in corner_indices:
        if idx not in seen:
            uniq.append(idx)
            seen.add(idx)
    corner_indices = sorted(uniq)
    if len(corner_indices) < 3:
        return contour  # не удалось надёжно найти углы — не трогаем контур

    result = []
    m = len(corner_indices)
    for i in range(m):
        i0 = corner_indices[i]
        i1 = corner_indices[(i + 1) % m]
        arc = contour[i0 : i1 + 1] if i1 > i0 else np.concatenate([contour[i0:], contour[: i1 + 1]])

        seg_lengths = np.linalg.norm(np.diff(arc, axis=0), axis=1)
        arc_len = float(np.sum(seg_lengths))
        n_seg = max(1, round(arc_len / max(target_edge_px, 1e-6)))

        result.append(arc[0])
        if n_seg > 1 and len(arc) > 2:
            cum = np.concatenate([[0.0], np.cumsum(seg_lengths)])
            for k in range(1, n_seg):
                target_len = arc_len * k / n_seg
                j = int(np.searchsorted(cum, target_len))
                j = min(max(j, 1), len(arc) - 1)
                seg_start_len, seg_end_len = cum[j - 1], cum[j]
                t = 0.0 if seg_end_len <= seg_start_len else (target_len - seg_start_len) / (seg_end_len - seg_start_len)
                result.append(arc[j - 1] + t * (arc[j] - arc[j - 1]))

    return np.array(result, dtype=np.float64)


# --------------------------------------------------------------------------
# Шаги 5-6: триангуляция полигона с дырками (mapbox_earcut)
# --------------------------------------------------------------------------

def _triangulate_with_holes(outer: np.ndarray, holes: list[np.ndarray], target_edge_px: float = 0.0):
    """Триангуляция полигона с дырками.

    Используется constrained Delaunay (библиотека `triangle`, порт
    Shewchuk's Triangle), а не earcut: earcut (ear clipping) даёт
    корректную, но геометрически некачественную триангуляцию — рядом с
    дырками получается "веер" тонких треугольников из одной-двух
    вершин-мостиков, которые почти не сливаются в квады.

    Если target_edge_px > 0, дополнительно включается качественный режим
    (флаги 'q28a<area>'): ограничение на минимальный угол (28°) и
    максимальную площадь треугольника (~(target_edge_px)^2/2) — без
    этого длинные узкие прямые участки (лента без изгибов) триангулируются
    зигзагом по диагонали, поскольку одних граничных точек недостаточно,
    чтобы "чётко" разбить полосу на ровные секции. Это добавляет
    вспомогательные (Steiner) точки внутри контура — цена за то, чтобы
    прямые узкие ленты давали ровные квады, а не диагональные полоски.

    Гарантия отсутствия самопересечений не зависит от этого флага:
    'p' в любом случае триангулирует ровно заданный PSLG (планарный
    прямолинейный граф), и добавление внутренних точек не может
    создать пересечение с границей.
    """
    try:
        import triangle as tr
    except ImportError:
        return _triangulate_with_holes_earcut(outer, holes)

    rings = [outer] + holes
    verts = np.concatenate(rings, axis=0).astype(np.float64)

    edges = []
    offset = 0
    for r in rings:
        n = len(r)
        edges.extend((offset + i, offset + (i + 1) % n) for i in range(n))
        offset += n

    from quad_mesh import _hole_marker
    hole_markers = [_hole_marker(h) for h in holes]

    pslg = {"vertices": verts, "segments": np.array(edges, dtype=np.int32)}
    if hole_markers:
        pslg["holes"] = np.array(hole_markers, dtype=np.float64)

    if target_edge_px and target_edge_px > 0:
        max_area = 0.9 * target_edge_px * target_edge_px
        opts = f"pq20a{max_area:.4f}"
    else:
        opts = "p"

    result = tr.triangulate(pslg, opts)
    out_verts = np.asarray(result["vertices"], dtype=np.float64)
    tris = np.asarray(result["triangles"], dtype=np.int64)

    if opts == "p" and len(out_verts) != len(verts):
        # 'p' без качественного режима не должен добавлять точки, но на
        # всякий случай — честный fallback на earcut, а не тихая порча
        # индексации
        return _triangulate_with_holes_earcut(outer, holes)

    return out_verts, tris


def _triangulate_with_holes_earcut(outer: np.ndarray, holes: list[np.ndarray]):
    import mapbox_earcut as earcut

    rings = [outer] + holes
    verts = np.concatenate(rings, axis=0).astype(np.float64)

    ring_ends = []
    acc = 0
    for r in rings:
        acc += len(r)
        ring_ends.append(acc)
    # mapbox_earcut (nanobind) ожидает КОНЕЦ каждого кольца, включая
    # внешнее; последнее значение обязано равняться числу вершин.
    ring_end_indices = np.array(ring_ends, dtype=np.uint32)

    tri_idx = earcut.triangulate_float64(verts, ring_end_indices)
    tris = tri_idx.reshape(-1, 3)
    return verts, tris


# --------------------------------------------------------------------------
# Шаг 7: слияние треугольников в квады (жадно, по общему ребру)
# --------------------------------------------------------------------------

def _angle(a, b, c) -> float:
    """Угол в вершине b треугольника/четырёхугольника abc, в градусах."""
    v1 = a - b
    v2 = c - b
    n1 = np.linalg.norm(v1)
    n2 = np.linalg.norm(v2)
    if n1 < 1e-12 or n2 < 1e-12:
        return 180.0
    cosang = np.clip(np.dot(v1, v2) / (n1 * n2), -1.0, 1.0)
    return math.degrees(math.acos(cosang))


def _is_reasonable_quad(pts: np.ndarray, angle_tol_deg: float) -> bool:
    """pts — 4 точки в порядке обхода. Проверяем выпуклость и что углы
    не вырождены (не слишком острые/тупые сверх допуска)."""
    n = len(pts)
    cross_signs = []
    for i in range(n):
        a, b, c = pts[i - 1], pts[i], pts[(i + 1) % n]
        v1 = b - a
        v2 = c - b
        cross = v1[0] * v2[1] - v1[1] * v2[0]
        cross_signs.append(np.sign(cross))
    if len(set(s for s in cross_signs if s != 0)) > 1:
        return False  # не выпуклый

    for i in range(n):
        a, b, c = pts[i - 1], pts[i], pts[(i + 1) % n]
        ang = _angle(a, b, c)
        if ang < angle_tol_deg or ang > (180 - angle_tol_deg):
            return False
    return True


def _merge_triangles_to_quads(verts: np.ndarray, tris: np.ndarray, p: Params):
    """Жадное слияние: для каждой пары треугольников с общим ребром
    пробуем построить квад; берём его, если он "приличный" (выпуклый,
    без вырожденных углов). Иначе оставляем оба треугольника как есть."""

    edge_to_tri: dict[tuple[int, int], list[int]] = {}
    for ti, tri in enumerate(tris):
        for i in range(3):
            a, b = int(tri[i]), int(tri[(i + 1) % 3])
            key = (a, b) if a < b else (b, a)
            edge_to_tri.setdefault(key, []).append(ti)

    used = [False] * len(tris)
    faces: list[tuple[int, ...]] = []

    for key, tri_ids in edge_to_tri.items():
        if len(tri_ids) != 2:
            continue
        t1, t2 = tri_ids
        if used[t1] or used[t2]:
            continue

        shared = set(key)
        verts1 = [int(x) for x in tris[t1]]
        verts2 = [int(x) for x in tris[t2]]
        opp1 = [v for v in verts1 if v not in shared][0]
        opp2 = [v for v in verts2 if v not in shared][0]
        a, b = key

        # порядок обхода квада: opp1, a, opp2, b
        quad_idx = [opp1, a, opp2, b]
        pts = verts[quad_idx]
        if _is_reasonable_quad(pts, p.quad_merge_angle_tol_deg):
            faces.append(tuple(quad_idx))
            used[t1] = True
            used[t2] = True

    for ti, tri in enumerate(tris):
        if not used[ti]:
            faces.append(tuple(int(x) for x in tri))

    return faces


def _quad_quality(pts: np.ndarray) -> float:
    """Оценка "квадратности" четырёхугольника: ближе к 1.0 для формы,
    близкой к квадрату/прямоугольнику с прямыми углами, ниже для
    вытянутых или перекошенных."""
    n = len(pts)
    edges = [np.linalg.norm(pts[(i + 1) % n] - pts[i]) for i in range(n)]
    if min(edges) < 1e-9:
        return -1.0
    aspect = min(edges) / max(edges)

    angle_dev = 0.0
    for i in range(n):
        a, b, c = pts[i - 1], pts[i], pts[(i + 1) % n]
        angle_dev += abs(_angle(a, b, c) - 90.0)
    angle_score = max(0.0, 1.0 - (angle_dev / n) / 90.0)

    return 0.5 * aspect + 0.5 * angle_score


def _merge_triangles_to_quads_quality(
    verts: np.ndarray, tris: np.ndarray, p: Params
) -> list[tuple[int, ...]]:
    """Слияние соседних треугольников в квады — но не в произвольном
    порядке перебора рёбер (как в жадной _merge_triangles_to_quads),
    а по ПРИОРИТЕТУ качества: сперва считаем оценку "квадратности" для
    КАЖДОЙ допустимой пары, затем объединяем лучшие пары первыми. Это
    даёт заметно более квадратные/прямоугольные грани и не зависит от
    случайного порядка ключей словаря, как раньше."""

    edge_to_tri: dict[tuple[int, int], list[int]] = {}
    for ti, tri in enumerate(tris):
        for i in range(3):
            a, b = int(tri[i]), int(tri[(i + 1) % 3])
            key = (a, b) if a < b else (b, a)
            edge_to_tri.setdefault(key, []).append(ti)

    candidates = []
    for key, tri_ids in edge_to_tri.items():
        if len(tri_ids) != 2:
            continue
        t1, t2 = tri_ids
        shared = set(key)
        v1 = [int(x) for x in tris[t1]]
        v2 = [int(x) for x in tris[t2]]
        opp1 = [v for v in v1 if v not in shared][0]
        opp2 = [v for v in v2 if v not in shared][0]
        a, b = key
        quad_idx = [opp1, a, opp2, b]
        pts = verts[quad_idx]
        if not _is_reasonable_quad(pts, p.quad_merge_angle_tol_deg):
            continue
        candidates.append((_quad_quality(pts), t1, t2, tuple(quad_idx)))

    candidates.sort(key=lambda c: -c[0])

    used = [False] * len(tris)
    faces: list[tuple[int, ...]] = []
    for _score, t1, t2, quad_idx in candidates:
        if used[t1] or used[t2]:
            continue
        faces.append(quad_idx)
        used[t1] = True
        used[t2] = True

    for ti, tri in enumerate(tris):
        if not used[ti]:
            faces.append(tuple(int(x) for x in tri))

    return faces


def _signed_area_2d(pts: np.ndarray) -> float:
    """Площадь по шнурку (shoelace); знак = ориентация (CCW>0, CW<0)."""
    x = pts[:, 0]
    y = pts[:, 1]
    return 0.5 * float(np.sum(x * np.roll(y, -1) - np.roll(x, -1) * y))


def _fix_winding(verts2d: np.ndarray, faces: list[tuple[int, ...]]) -> list[tuple[int, ...]]:
    """Разворачивает все грани в единую (CCW) ориентацию.

    Баг, который это чинит: earcut и жадное слияние в квады не гарантируют
    одинаковый обход вершин у разных граней, из-за чего в Blender часть
    полигонов оказывается "вывернута" (нормали смотрят в разные стороны).
    """
    fixed = []
    for f in faces:
        pts = verts2d[list(f)]
        if _signed_area_2d(pts) < 0:
            f = tuple(reversed(f))
        fixed.append(f)
    return fixed


def drop_degenerate_faces(
    verts2d: np.ndarray, faces: list[tuple[int, ...]], min_area: float = 1e-6
) -> list[tuple[int, ...]]:
    """Убирает грани нулевой/почти нулевой площади, а также грани с дублирующимися вершинами."""
    out = []
    for f in faces:
        if len(set(f)) < 3:
            continue
        pts = verts2d[list(f)]
        if abs(_signed_area_2d(pts)) > min_area:
            out.append(f)
    return out


